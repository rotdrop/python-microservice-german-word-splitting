"""Environment-driven settings."""

import os
from dataclasses import dataclass

DICTIONARY_ENV = "GERMAN_WORD_SPLITTER_DICTIONARY"
FALLBACK_DICTIONARY = "german_utf8_linux.dic"
LOCALES_ENV = "GERMAN_WORD_SPLITTER_TRANSLITERATION_LOCALES"
PORT_ENV = "GERMAN_WORD_SPLITTER_PORT"
SOCKET_ENV = "GERMAN_WORD_SPLITTER_SOCKET"
PORT_FILE_ENV = "GERMAN_WORD_SPLITTER_PORT_FILE"
SOCKET_MODE_ENV = "GERMAN_WORD_SPLITTER_SOCKET_MODE"
FALLBACK_PORT = 8000
FALLBACK_SOCKET_MODE = 0o660

try:  # generated by `make install`
    from ._default_dictionary import DEFAULT_DICTIONARY
except ImportError:
    DEFAULT_DICTIONARY = FALLBACK_DICTIONARY

try:  # generated by `make install PORT=...`
    from ._default_port import DEFAULT_PORT
except ImportError:
    DEFAULT_PORT = FALLBACK_PORT

try:  # generated by `make install SOCKET=1`
    from ._default_socket import DEFAULT_SOCKET
except ImportError:
    DEFAULT_SOCKET = None


def get_port() -> int:
    return int(os.environ.get(PORT_ENV, DEFAULT_PORT))


def get_socket() -> str | None:
    """Path of the Unix domain socket to listen on, or None to use TCP."""
    return os.environ.get(SOCKET_ENV) or DEFAULT_SOCKET


def get_port_file() -> str | None:
    """File to which the effective TCP port is written (useful with port 0)."""
    return os.environ.get(PORT_FILE_ENV) or None


def get_socket_mode() -> int:
    """Permission bits of the Unix socket, given in octal (default 660)."""
    value = os.environ.get(SOCKET_MODE_ENV)
    return int(value, 8) if value else FALLBACK_SOCKET_MODE


def get_transliteration_locales() -> tuple[str, ...]:
    """Locales (comma or whitespace separated) used to transliterate the dictionary."""
    return tuple(os.environ.get(LOCALES_ENV, "").replace(",", " ").split())


@dataclass(frozen=True)
class Settings:
    dictionary_path: str = DEFAULT_DICTIONARY
    transliteration_locales: tuple[str, ...] = ()


def get_settings() -> Settings:
    return Settings(
        dictionary_path=os.environ.get(DICTIONARY_ENV, DEFAULT_DICTIONARY),
        transliteration_locales=get_transliteration_locales(),
    )
